CREATE INDEX ix_plan_account ON plan (account_id);
-- goals_json holds the before/after/how goals. They are only ever read and written with
-- the plan, never queried across plans, so they do not earn a table.

CREATE TABLE plan_slot (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id      BIGINT      NOT NULL REFERENCES plan(id) ON DELETE CASCADE,
  session_id   BIGINT      NOT NULL,
  session_kind VARCHAR(16) NOT NULL DEFAULT 'session',
  weekday      INTEGER     NOT NULL,
  week         INTEGER     NOT NULL DEFAULT 0,
  CONSTRAINT fk_slot_session FOREIGN KEY (session_id, session_kind)
    REFERENCES content (id, kind) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT ck_slot_session_kind CHECK (session_kind = 'session'),
  CONSTRAINT ck_slot_weekday CHECK (weekday BETWEEN 1 AND 7),
  CONSTRAINT ck_slot_week    CHECK (week >= 0),
  CONSTRAINT ux_slot UNIQUE (plan_id, week, weekday, session_id)
);
-- week 0 means every week. Not NULL: a nullable column in a unique key is not enforced,
-- because NULLs compare distinct.

-- What a cycle asks of one exercise. This is the Exercise targets page.
CREATE TABLE plan_target (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id       BIGINT      NOT NULL REFERENCES plan(id) ON DELETE CASCADE,
  movement_id   BIGINT      NOT NULL,
  movement_kind VARCHAR(16) NOT NULL DEFAULT 'movement',
  week          INTEGER     NOT NULL DEFAULT 0,
  sets          INTEGER,
  reps          INTEGER,
  weight_kg     NUMERIC(6,2),
  rep_seconds   INTEGER,
  CONSTRAINT fk_target_movement FOREIGN KEY (movement_id, movement_kind)
    REFERENCES content (id, kind) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT ck_target_movement_kind CHECK (movement_kind = 'movement'),
  CONSTRAINT ck_target_week CHECK (week >= 0),
  CONSTRAINT ux_target UNIQUE (plan_id, movement_id, week)
);
-- week 0 is the whole cycle; 1..n is that week only.
--
-- "Varies by week" is NOT a stored flag. It is true when a week > 0 row exists for that
-- plan and movement. A flag could disagree with the rows; a derived answer cannot.
--
-- A target is per movement per plan, so one row covers that movement wherever it appears
-- in the cycle. That is the intent of the page: "this cycle asks 5x5 of weighted
-- pull-ups", not "5x5 in Tuesday's session only".

CREATE TABLE scheduled (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id   BIGINT      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  plan_id      BIGINT      REFERENCES plan(id) ON DELETE CASCADE,
  session_id   BIGINT      NOT NULL,
  session_kind VARCHAR(16) NOT NULL DEFAULT 'session',
  on_date      VARCHAR(10) NOT NULL,
  position     INTEGER     NOT NULL DEFAULT 0,
  created_at   TIMESTAMP   NOT NULL,
  CONSTRAINT fk_sched_session FOREIGN KEY (session_id, session_kind)
    REFERENCES content (id, kind) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,
  CONSTRAINT ck_sched_session_kind CHECK (session_kind = 'session'),
  CONSTRAINT ck_sched_on_date      CHECK (length(on_date) = 10)
);
CREATE INDEX ix_sched_account ON scheduled (account_id, on_date);
CREATE INDEX ix_sched_plan    ON scheduled (plan_id);
-- plan_id is nullable because a session can be scheduled by hand with no cycle behind it.
-- No natural key is possible as a result: the same session twice on one day is legal, and
-- position tells them apart. Duplicate prevention is the app's job, not a constraint's.

CREATE TABLE calendar_event (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT       NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  plan_id    BIGINT       REFERENCES plan(id) ON DELETE CASCADE,
  title      VARCHAR(128) NOT NULL,
  kind       VARCHAR(32)  NOT NULL,
  from_date  VARCHAR(10)  NOT NULL,
  to_date    VARCHAR(10)  NOT NULL,
  blocks     BOOLEAN      NOT NULL DEFAULT TRUE,
  notes      TEXT         NOT NULL DEFAULT '',
  CONSTRAINT ck_event_kind  CHECK (kind IN ('trip','injury','rest','competition','other')),
  -- ck_event_range compares two strings, so a short date does not just sort wrong, it
  -- passes or fails the range test wrongly. These two checks are what make it mean
  -- anything.
  CONSTRAINT ck_event_from  CHECK (length(from_date) = 10),
  CONSTRAINT ck_event_to    CHECK (length(to_date)   = 10),
  CONSTRAINT ck_event_range CHECK (to_date >= from_date)
);
CREATE INDEX ix_event_account ON calendar_event (account_id, from_date);


