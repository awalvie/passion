CREATE TABLE account (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                VARCHAR(255) NOT NULL,
  password_hash        VARCHAR(255) NOT NULL,
  height_cm            INTEGER,
  ape_index_cm         INTEGER,
  boulder_grade_system VARCHAR(32)  NOT NULL DEFAULT 'font',
  route_grade_system   VARCHAR(32)  NOT NULL DEFAULT 'french',
  max_pull_ups         INTEGER,
  max_hang_kg          NUMERIC(5,2),

  -- "Today" must be the athlete's day, not the server's. Every heatmap, streak and
  -- calendar boundary depends on it.
  time_zone            VARCHAR(64)  NOT NULL DEFAULT 'UTC',

  -- Carried as a JWT claim and compared on every request. Changing a password bumps it,
  -- which is the only way a stateless token can be revoked before it expires.
  token_epoch          INTEGER      NOT NULL DEFAULT 0,
  created_at           TIMESTAMP    NOT NULL,
  updated_at           TIMESTAMP    NOT NULL,
  CONSTRAINT ux_account_email UNIQUE (email)
);
-- Email is folded to lowercase in Go before every read and write. Never left to the
-- database collation.

