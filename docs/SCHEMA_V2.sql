-- ===========================================================================
-- THE LOG  --  frozen. reads no content table, ever.
-- ===========================================================================
--
-- UUID keys, because a phone with no signal creates these rows.
-- updated_at on all four, because sync has to know what changed.
--
-- Sync is phone to this server and back, and never device to device. That is why a log row
-- may point at content by the local integer movement_id: both ends share one database. If
-- that ever changes, log_entry needs the content uuid beside movement_family -- family to
-- group, uuid to identify -- and it is a NOT NULL text column, so migration 001 or never.
--
-- Every name shown here is this table's own copy. Drop every content table and the whole
-- of history still renders. That is the rule, and place_name is part of it: reading the
-- venue name live would mean renaming a gym rewrites your history.

CREATE TABLE log (
  -- NOT NULL is spelled out: SQLite allows a NULL in a PRIMARY KEY unless the column is
  -- INTEGER PRIMARY KEY, and this one is not.
  id           VARCHAR(36)  PRIMARY KEY NOT NULL,
  account_id   BIGINT       NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  on_date      VARCHAR(10)  NOT NULL,

  scheduled_id BIGINT       REFERENCES scheduled(id) ON DELETE SET NULL,

  -- Four columns, the same four log_entry carries for a movement, for the same reasons.
  -- session_family is what "times completed" counts, and it is NOT the name: a person's
  -- session called Power and the app's session called Power are two workouts, and counting
  -- them together was the fault this column removes.
  --
  -- Empty when a run had no session behind it -- an open session is not a template, so it
  -- belongs to no family and is counted by nothing.
  session_id     BIGINT       REFERENCES content(id) ON DELETE SET NULL,
  session_family VARCHAR(36)  NOT NULL DEFAULT '',
  session_slug   VARCHAR(128) NOT NULL DEFAULT '',
  session_name   VARCHAR(255) NOT NULL DEFAULT '',
  color        VARCHAR(16)  NOT NULL DEFAULT '',

  place_id     BIGINT       REFERENCES place(id) ON DELETE SET NULL,
  place_name   VARCHAR(128) NOT NULL DEFAULT '',
  place_kind   VARCHAR(16)  NOT NULL DEFAULT '',

  state        VARCHAR(16)  NOT NULL,
  started_at   TIMESTAMP,
  ended_at     TIMESTAMP,

  sleep        INTEGER,
  energy       INTEGER,
  rpe          INTEGER,
  focus        VARCHAR(32)  NOT NULL DEFAULT '',
  setting      VARCHAR(16)  NOT NULL DEFAULT '',

  went_well    TEXT         NOT NULL DEFAULT '',
  next_focus   TEXT         NOT NULL DEFAULT '',
  notes        TEXT         NOT NULL DEFAULT '',

  created_at   TIMESTAMP    NOT NULL,
  updated_at   TIMESTAMP    NOT NULL,

  CONSTRAINT ck_log_state CHECK (state IN ('draft','active','done','abandoned')),

  -- Every date index and every history sort compares this as text, so a date written
  -- 2026-9-7 instead of 2026-09-07 sorts before every other September date, for good.
  CONSTRAINT ck_log_on_date CHECK (length(on_date) = 10),

  -- Either a real family or nothing. See ck_content_family: NOT NULL alone lets a short
  -- value through, and a short value silently joins every other short value into one count.
  CONSTRAINT ck_log_session_family CHECK (session_family = '' OR length(session_family) = 36)
);
CREATE INDEX ix_log_account ON log (account_id, on_date);
CREATE INDEX ix_log_session ON log (session_id);
CREATE INDEX ix_log_sync    ON log (account_id, updated_at);
CREATE INDEX ix_log_state   ON log (account_id, state);
-- "how many times have I done this session" -- the mirror of ix_entry_movement one level
-- down. Partial, because an open session has no family and would otherwise fill the index
-- with one repeated empty value.
CREATE INDEX ix_log_family  ON log (session_family, account_id) WHERE session_family <> '';
-- draft is a manual entry still being typed in. Hidden from history until saved.
-- A log with no entries is a journal entry. Not a second table.

CREATE TABLE log_entry (
  -- NOT NULL is spelled out for the reason given on log.id.
  id            VARCHAR(36)  PRIMARY KEY NOT NULL,
  log_id        VARCHAR(36)  NOT NULL REFERENCES log(id) ON DELETE CASCADE,

  position      INTEGER      NOT NULL,
  block_name    VARCHAR(255) NOT NULL DEFAULT '',
  block_kind    VARCHAR(16)  NOT NULL DEFAULT '',

  -- Four columns, four jobs.
  --
  --   movement_id      the row that was run. Goes NULL if that row is deleted outright.
  --   movement_family  the identity history groups by. Text, so it survives that delete.
  --   movement_slug    what the file called it that day.
  --   movement_name    what was on screen that day.
  --
  -- The last two are why the whole of history renders with every content table dropped.
  -- This mirrors log.session_id / session_slug / session_name one level up.
  --
  -- History groups on the family and NOT on the slug. Two reasons. A slug can be taken by
  -- two unrelated movements -- yours and the app's -- and grouping on it silently merges
  -- them into one chart. And a rename would have to rewrite these rows to keep a chart
  -- whole, which is a destructive write against history; the family never changes, so
  -- there is nothing to rewrite.
  movement_id     BIGINT       REFERENCES content(id) ON DELETE SET NULL,
  movement_family VARCHAR(36)  NOT NULL,
  movement_slug   VARCHAR(128) NOT NULL,
  movement_name   VARCHAR(255) NOT NULL,

  -- How the movement was performed. Frozen, because changing a movement's style later
  -- must not change how an old run is drawn.
  movement_style VARCHAR(32) NOT NULL DEFAULT '',

  -- what was asked of you that day
  t_sets        INTEGER,
  t_reps        INTEGER,
  t_weight_kg   NUMERIC(6,2),
  t_rep_seconds      INTEGER,
  t_rep_rest_seconds INTEGER,
  t_set_rest_seconds INTEGER,
  t_prep_seconds     INTEGER,
  t_seconds          INTEGER,

  -- what happened
  state           VARCHAR(16) NOT NULL DEFAULT 'pending',
  elapsed_seconds INTEGER     NOT NULL DEFAULT 0,
  set_mode        VARCHAR(16) NOT NULL DEFAULT 'simple',
  climb_kind      VARCHAR(32) NOT NULL DEFAULT '',
  climb_subtype   VARCHAR(32) NOT NULL DEFAULT '',
  notes           TEXT        NOT NULL DEFAULT '',

  created_at    TIMESTAMP    NOT NULL,
  updated_at    TIMESTAMP    NOT NULL,

  CONSTRAINT ck_entry_state    CHECK (state IN ('pending','done','skipped')),
  CONSTRAINT ck_entry_set_mode CHECK (set_mode IN ('simple','per_set')),

  -- See ck_content_family. A manual entry with no library movement behind it gets its own
  -- fresh family, so it is a singleton and charts alone. Never the empty string, which
  -- would make every such entry one movement.
  CONSTRAINT ck_entry_family   CHECK (length(movement_family) = 36)
);
-- The progression query on the run screen -- "the last five times you did this" -- reads
-- this index by its leading column, then joins log by its primary key for the account and
-- the date. The join is what the removed frozen columns used to avoid, and it costs nothing
-- here: one account holds a few hundred logs.
-- Not bounded by account: log_entry no longer carries account_id, so a query for a shipped
-- movement reads every account's entries for that family and the join to log throws all but
-- yours away. Correct, and the work grows with the number of accounts rather than with your
-- own history. Irrelevant at any size this app will see; written down so it is not met
-- later as a mystery.
CREATE INDEX ix_entry_movement ON log_entry (movement_family, log_id);
CREATE INDEX ix_entry_log      ON log_entry (log_id, position);

-- One set: what was asked of it, and what you did. Both on the row, so an open session
-- with per-set planning needs nothing extra.
CREATE TABLE log_set (
  -- NOT NULL is spelled out for the reason given on log.id, and it matters most here:
  -- these are the rows a phone invents offline. Tested on SQLite -- two inserts with a
  -- NULL id both succeed, leaving two rows nothing can tell apart.
  id              VARCHAR(36) PRIMARY KEY NOT NULL,
  log_entry_id    VARCHAR(36) NOT NULL REFERENCES log_entry(id) ON DELETE CASCADE,
  set_index       INTEGER  NOT NULL,
  rep_index       INTEGER  NOT NULL DEFAULT 0,
  target_reps     INTEGER,
  target_weight_kg NUMERIC(6,2),
  target_seconds  INTEGER,
  reps            INTEGER,
  weight_kg       NUMERIC(6,2),
  seconds         INTEGER,
  updated_at      TIMESTAMP NOT NULL,
  CONSTRAINT ck_log_set_index CHECK (set_index >= 1),
  CONSTRAINT ck_log_rep_index CHECK (rep_index >= 0),
  CONSTRAINT ux_log_set UNIQUE (log_entry_id, set_index, rep_index)
);

CREATE TABLE log_climb (
  -- NOT NULL is spelled out for the reason given on log_set.id.
  id           VARCHAR(36) PRIMARY KEY NOT NULL,
  log_entry_id VARCHAR(36) NOT NULL REFERENCES log_entry(id) ON DELETE CASCADE,
  position     INTEGER     NOT NULL DEFAULT 0,
  kind         VARCHAR(16) NOT NULL,
  setting      VARCHAR(16) NOT NULL DEFAULT '',
  subtype      VARCHAR(32) NOT NULL DEFAULT '',
  grade        VARCHAR(32) NOT NULL DEFAULT '',
  grade_ordinal INTEGER,
  style        VARCHAR(32) NOT NULL DEFAULT '',
  rope_style   VARCHAR(32) NOT NULL DEFAULT '',
  attempts     INTEGER     NOT NULL DEFAULT 0,
  sent         BOOLEAN     NOT NULL DEFAULT FALSE,
  seconds      INTEGER     NOT NULL DEFAULT 0,
  stars        INTEGER     NOT NULL DEFAULT 0,
  focus        TEXT        NOT NULL DEFAULT '',
  thoughts     TEXT        NOT NULL DEFAULT '',
  updated_at   TIMESTAMP   NOT NULL,
  CONSTRAINT ck_climb_kind  CHECK (kind IN ('boulder','sport','trad')),
  CONSTRAINT ck_climb_stars CHECK (stars BETWEEN 0 AND 3)
);
CREATE INDEX ix_climb_entry ON log_climb (log_entry_id, position);
-- grade_ordinal is what makes a pyramid sortable. Nullable, because an ARC lap or a
-- traverse has no grade.
--
-- Climbing is the one kind with no per-set target. There is no "asked 4x3" for
-- bouldering. Its target is the whole step -- log_entry.t_seconds for time on the wall,
-- or t_reps for a problem count -- and these tick rows are the record of what happened.


-- ===========================================================================
-- WHERE A NUMBER COMES FROM
-- ===========================================================================
--
-- Starting a run, for one exercise in one block of one session, in a cycle.
-- First match wins. NULL at a level means "not set here" and falls through.
--
--   1. content_item_set        this set specifically, if the block plans per set
--   2. plan_target week = N    what this cycle asks in week N
--   3. plan_target week = 0    what this cycle asks throughout
--   4. content_item            what the block asks
--   5. movement_pref           your own number for this movement
--   6. content.d_*             the movement's default
--
-- Whatever wins is copied into log_entry.t_* (and log_set.target_*) at the moment the
-- run is created, and is never recomputed. History shows what was asked, forever.
--
-- Alongside it, and never stored as a target, the run screen shows what you last did:
--
--   WITH last5 AS (
--     SELECT e.id, l.on_date
--     FROM   log_entry e
--     JOIN   log l ON l.id = e.log_id
--     WHERE  e.movement_family = :family
--       AND  l.account_id = :me
--       AND  e.state = 'done'
--     ORDER BY l.on_date DESC, e.id DESC
--     LIMIT  5)
--   SELECT last5.on_date, e.t_reps, s.reps, s.weight_kg
--   FROM   last5
--   JOIN   log_entry e ON e.id = last5.id
--   LEFT JOIN log_set s ON s.log_entry_id = e.id
--   ORDER BY last5.on_date DESC, s.set_index;
--
-- Three things the obvious spelling gets wrong, all found in review:
--
--   The LIMIT has to be on the ENTRIES. Joining log_set first fans one entry out to one row
--   per set, so LIMIT 5 on the joined rows returns five sets of one session, not five
--   sessions.
--   state = 'done' is required. ck_entry_state permits pending and skipped, so a hang you
--   skipped last week would come back as what you last did.
--   on_date needs a tiebreaker. Two logs on one day order arbitrarily without one.
--
-- Read from ix_entry_movement by its leading column, then log by primary key. Touches no
-- content table, so the whole of history answers with every content row deleted.


-- ===========================================================================
-- EDITING
-- ===========================================================================
--
-- Three cases, three answers. None of them makes a hidden copy.
--
-- 1. A row you own that came from a file. Edited IN PLACE: same id, same slug, and
--    source_tree set to NULL. The NULL is what stops the next re-import overwriting the
--    edit, and it detaches the row from its file for good. Nothing about your history
--    changes, because the slug did not move.
--
--    The import report names every row it skipped this way, and the library badges them.
--    Without that, a person edits the YAML file, restarts, sees no change, and is told
--    nothing -- and this project's owner hand-edits those files as his main way of working.
--
-- 2. Only the numbers on a movement the app ships. That is movement_pref, not an edit.
--    No new row, no new identity, nothing to reconcile later.
--
-- 3. The structure of something the app ships. That is an explicit "copy to my content"
--    action in the UI, never an implicit one. The copy gets a NEW uuid and INHERITS THE
--    FAMILY, which is what holds your history together across it.
--
--    Copying something the APP ships also keeps the slug, because your names and the app's
--    live in separate unique indexes. Copying something YOU ALREADY OWN cannot: same
--    author, same kind, same slug is refused by ux_content_mine, so the UI must rename.
--    That is the case where the family earns its keep most plainly -- the renamed copy
--    still charts with the row it came from.
--
--    A copy never keeps the original's uuid. Every comparable project that allowed that
--    lost a row to it -- Anki, Logseq, Grafana, Pulumi and Argo CD all document the same
--    failure, where two things sharing one id read as one thing in two states.
--
--    A copy takes the thing and its structure, and stops before the movements:
--
--      copy a session  ->  new session row, new block rows, new content_item edges.
--                          the edges still point at the SAME movement rows.
--      copy a block    ->  new block row and its edges. same movements.
--      copy a movement ->  one new row. media copied.
--
--    Consequence worth saying in the copy dialog: your YAML files still say app:<slug>,
--    so a session you run from a file keeps using the app's row. There is no fallback by
--    design, so nothing silently switches to the copy.
--
-- What is NOT here, and why:
--
--   No replaced_by pointer. wger ships one: upstream publishes "this exercise is gone, use
--   that one", and the importer moves the user's log rows onto the replacement inside a
--   transaction. It needs a guaranteed import order and a fallback for a missing target,
--   and wger gets both wrong -- its own test records the result, which is that a user's
--   logs are deleted.
--
--   We drop a shipped movement about once a year, and retired_on already keeps its history
--   working: the row stays, so the old chart keeps rendering. What retired_on does NOT do
--   is join the old chart to the new movement's, and neither does the family on its own --
--   a replacement is a new file with a new id, so its family is its own.
--
--   Joining them is one line, written by hand in the replacement file:
--
--     # movements/hanging_leg_raises.yaml -- replaces hanging_knee_raises
--     id:     <new>
--     family: <the retired movement's id>
--
--   A person doing that deliberately, in a file, in a commit, is worth more than an
--   automatic write against finished history.
--
--   No forked_from_id, and no parent pointer of any kind. The family is flat. A copy and
--   the row it came from are found by (kind, slug) across the two unique indexes, and
--   "reset to the app's version" is deleting your copy.
--
-- Renaming needs no mechanism at all. The importer matches a file to a row by its uuid, so
-- renaming the file, moving it between directories, or changing its slug all land on the
-- same row and update it in place. Nothing is written to the log, because the family did
-- not move. What a rename still costs is the refs: another file naming the old slug now
-- names nothing, and the importer must say which files broke, in the same commit.


-- ===========================================================================
-- WHAT GORM CANNOT EXPRESS
-- ===========================================================================
--
-- AutoMigrate handles the tables, columns, plain indexes, and the partial unique indexes
-- via `uniqueIndex:...,where:...` -- verified: the sqlite and postgres drivers both emit
-- the predicate. The following need explicit statements beside it, identical on both
-- engines:
--
--   1. The six composite foreign keys into content (id, kind): content_item x2, plan_slot,
--      plan_target, scheduled, movement_pref. GORM has no struct tag for a multi-column
--      reference. log_entry.movement_id is a plain single-column FK and is not one of them.
--   2. UNIQUE (id, kind) on content, since it exists only to be a foreign key target.
--   3. The partial unique indexes on uuid, and ix_log_family, which carry a WHERE clause
--      GORM's uniqueIndex tag can express but a plain index tag cannot.
--
-- SQLite cannot add a CHECK to an existing table, so every CHECK above has to be present
-- when the table is first created. That makes the initial migration a create, never an
-- alter, and it means these statements run in order at first boot.
