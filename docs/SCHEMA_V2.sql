CREATE TABLE grade_milestone (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id    BIGINT      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  taken_on      VARCHAR(10) NOT NULL,
  discipline    VARCHAR(16) NOT NULL,
  grade         VARCHAR(32) NOT NULL,
  grade_ordinal INTEGER     NOT NULL,
  CONSTRAINT ck_grade_discipline CHECK (discipline IN ('boulder','route')),
  CONSTRAINT ck_grade_taken_on   CHECK (length(taken_on) = 10),
  CONSTRAINT ux_grade_milestone  UNIQUE (account_id, discipline, taken_on)
);
-- grade_ordinal exists so progression can be sorted and charted. A grade held only as
-- text cannot be ordered in SQL at all.


-- ===========================================================================
-- CONTENT  --  one table for what the app ships and what a user writes
-- ===========================================================================

CREATE TABLE content (
  -- The local key. Every foreign key in this schema points here, and nothing else does.
  -- It is allowed to differ between two installs of the app and it never leaves the
  -- machine.
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- The global key. It is written in the YAML file, and it is the only identity that
  -- crosses a machine boundary. The importer matches a file to a row on this column, so a
  -- file can be renamed, moved between directories, or have its slug changed, and the row
  -- it owns is still the same row. It is never a foreign key target.
  --
  -- The id has to be IN THE FILE. An id minted at import time is lost the moment a tree is
  -- exported and restored into a fresh database, which is what killed the earlier
  -- content_key design. A row created in the app gets its uuid at insert instead.
  --
  -- wger runs this exact split: uuid to match across installs, integer pk for every join.
  uuid           VARCHAR(36)  NOT NULL,

  -- Which family of rows this one belongs to. Read by history, and by nothing else.
  --
  -- A new row's family is its own uuid. A copy inherits the family of the row it came
  -- from, unchanged, for good. So the app's "Pull Up" and your copy of it share a family,
  -- and one progression chart covers both.
  --
  -- Flat, and never followed. Nothing resolves a family value to a row, so there is no
  -- parent chain to walk and none to rot. wger reached the same shape from the other
  -- direction: it had a Variation table, and migration 0037 deleted it for one indexed
  -- UUID column on the row, because a local group row cannot survive a sync.
  family         VARCHAR(36)  NOT NULL,

  kind           VARCHAR(16)  NOT NULL,
  slug           VARCHAR(128) NOT NULL,
  name           VARCHAR(255) NOT NULL,

  -- Which catalog tree owns this row, or NULL when nothing does.
  --
  -- A re-import rewrites the rows whose source_tree matches the tree being imported. A row
  -- with NULL here is skipped and named in the import report. That is what keeps a YAML
  -- file meaningful after its first import, and what stops a boot erasing something typed
  -- in the app.
  --
  -- Editing a file-owned row in the app sets this to NULL, which detaches the row from its
  -- file for good. The file then has no effect and the app says so, both in the import
  -- report and on the row in the library.
  --
  -- A tree NAME, not its path: paths differ between machines. One nullable column instead
  -- of a boolean plus a name, because two columns can disagree and one cannot.
  source_tree    VARCHAR(64),

  -- NULL author means the app ships this row. No account holds it, so no account's
  -- deletion can reach it. There is no ON DELETE SET NULL on this column anywhere in
  -- the schema: that would silently publish a user's private content into the catalog.
  author_id      BIGINT       REFERENCES account(id) ON DELETE CASCADE,

  notes          TEXT         NOT NULL DEFAULT '',
  source         VARCHAR(64)  NOT NULL DEFAULT '',

  -- Set by the importer when a shipped slug leaves the YAML tree. The library hides these;
  -- plans and logs that reference them keep resolving. Two slugs have already been removed
  -- from the tree in the project's history.
  retired_on     VARCHAR(10),

  -- movement rows: how it is performed, which decides the run screen it gets.
  movement_style VARCHAR(32),

  -- TRUE when the numbers are per side. Without it, "1 set of 6, per side" can only be
  -- said in prose, and the player counts 6 when the athlete owes 12.
  per_side       BOOLEAN      NOT NULL DEFAULT FALSE,
  d_sets         INTEGER,
  d_reps         INTEGER,
  d_weight_kg    NUMERIC(6,2),
  d_rep_seconds      INTEGER,
  d_rep_rest_seconds INTEGER,
  d_set_rest_seconds INTEGER,
  d_prep_seconds     INTEGER,
  d_seconds          INTEGER,

  -- block rows
  block_kind     VARCHAR(16),

  -- menu rows: the FEWEST options you must pick, not the most. 0 is legal and means the
  -- menu may be skipped, which is the only place optionality can live -- the alternative
  -- is the word "optional" inside a display name, which nothing can act on.
  pick_count     INTEGER,

  -- session rows
  color          VARCHAR(16)  NOT NULL DEFAULT '',
  needs          VARCHAR(255) NOT NULL DEFAULT '',

  created_at     TIMESTAMP    NOT NULL,
  updated_at     TIMESTAMP    NOT NULL,

  CONSTRAINT ck_content_kind       CHECK (kind IN ('movement','menu','block','session')),
  CONSTRAINT ck_content_block_kind CHECK (block_kind IS NULL
                                          OR block_kind IN ('warmup','main','cooldown')),
  CONSTRAINT ck_content_style       CHECK (movement_style IS NULL
    OR movement_style IN ('climbing','open','reps_and_sets','timed_reps')),

  -- A menu must say how many options to pick, and nothing else may carry a count. "Pick
  -- NULL of these" has no meaning on the run screen, and a count on a block is dead data.
  CONSTRAINT ck_content_pick       CHECK (
       (kind =  'menu' AND pick_count IS NOT NULL AND pick_count >= 0)
    OR (kind <> 'menu' AND pick_count IS NULL)),

  -- A colon separates a namespace from a name in a reference, so a slug holding one would
  -- make "app:thing" ambiguous. LIKE is the only pattern match both engines share.
  CONSTRAINT ck_content_slug       CHECK (slug NOT LIKE '%:%'),

  -- Dates are compared and sorted as text, so a short one sorts wrong for good.
  CONSTRAINT ck_content_retired    CHECK (retired_on IS NULL OR length(retired_on) = 10),

  -- NOT NULL accepts the empty string, on both engines. Without these, one write path
  -- that forgets to set a family inserts '' and nothing complains -- and every row it
  -- touches then shares one family, so they all chart as one movement. The log is frozen,
  -- so there is no repair afterwards.
  CONSTRAINT ck_content_uuid       CHECK (length(uuid) = 36),
  CONSTRAINT ck_content_family     CHECK (length(family) = 36),

  -- The target of the composite foreign keys in content_item, plan_slot and scheduled.
  -- Redundant on its own; it is what lets those tables constrain WHICH KIND they point at.
  CONSTRAINT ux_content_id_kind    UNIQUE (id, kind)
);

-- Two partial unique indexes, not one. All engines treat NULLs in a unique key as
-- distinct, so a single UNIQUE(author_id, kind, slug) would let two shipped rows share a
-- slug. PostgreSQL and SQLite both support the predicate; MySQL does not, which is why
-- MySQL is out of scope.
CREATE UNIQUE INDEX ux_content_shipped ON content (kind, slug)            WHERE author_id IS NULL;
CREATE UNIQUE INDEX ux_content_mine    ON content (author_id, kind, slug) WHERE author_id IS NOT NULL;

-- Scoped to the owner, for the same reason the slug indexes above are. A global unique
-- index here would mean two accounts cannot both add the same published catalog directory:
-- whoever boots first takes the ids and the other account's import fails on every boot,
-- forever. Sharing a tree is the main way a catalog gets distributed, so that is backwards.
--
-- Scoped, it also makes copying a file DO THE RIGHT THING. Copy the app's movements/x.yaml
-- into your own tree unchanged and you get a second row in your own namespace holding the
-- same uuid, so the same family, so one chart. Copy a file WITHIN one tree and forget to
-- change its id, and that still collides -- which is the mistake this exists to catch, and
-- the single most reported failure in every comparable project.
CREATE UNIQUE INDEX ux_content_uuid_shipped ON content (uuid)            WHERE author_id IS NULL;
CREATE UNIQUE INDEX ux_content_uuid_mine    ON content (author_id, uuid) WHERE author_id IS NOT NULL;

-- Not unique, on purpose. Every row in one family carries the same value.
CREATE INDEX ix_content_family ON content (family);

CREATE INDEX ix_content_author ON content (author_id);
CREATE INDEX ix_content_kind   ON content (kind);
CREATE INDEX ix_content_list   ON content (author_id, kind, name);


-- Every edge in the content tree, and the prescribed numbers for that use.
--
-- The numbers live HERE and not on the movement. That is what lets one movement row be
-- referenced by every session that uses it, and it is what wger does for the same reason.
--
-- The kind columns are duplicated from content, but a composite foreign key keeps each
-- one honest, so they cannot disagree. Enumerating the legal pairs makes a cycle
-- structurally impossible -- there is no legal edge from a movement to anything.
CREATE TABLE content_item (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  parent_id        BIGINT      NOT NULL,
  parent_kind      VARCHAR(16) NOT NULL,
  child_id         BIGINT      NOT NULL,
  child_kind       VARCHAR(16) NOT NULL,

  position         INTEGER     NOT NULL,

  sets             INTEGER,
  reps             INTEGER,
  weight_kg        NUMERIC(6,2),
  rep_seconds      INTEGER,
  rep_rest_seconds INTEGER,
  set_rest_seconds INTEGER,
  prep_seconds     INTEGER,
  seconds          INTEGER,
  notes            TEXT        NOT NULL DEFAULT '',

  CONSTRAINT fk_item_parent FOREIGN KEY (parent_id, parent_kind)
    REFERENCES content (id, kind) ON DELETE CASCADE,
  -- Deferrable, not RESTRICT. Deleting an account cascades content and its edges in one
  -- statement, and Postgres checks a RESTRICT row-by-row mid-cascade and refuses, while
  -- SQLite allows it. Same DDL, opposite behaviour. Tested. Deferring the check to commit
  -- makes both engines agree.
  CONSTRAINT fk_item_child  FOREIGN KEY (child_id, child_kind)
    REFERENCES content (id, kind) ON DELETE NO ACTION DEFERRABLE INITIALLY DEFERRED,

  CONSTRAINT ck_item_pair CHECK (
       (parent_kind = 'session' AND child_kind = 'block')
    OR (parent_kind = 'block'   AND child_kind IN ('movement','menu'))
    OR (parent_kind = 'menu'    AND child_kind = 'movement')
  ),
  CONSTRAINT ck_item_not_self CHECK (parent_id <> child_id),
  CONSTRAINT ck_item_position  CHECK (position >= 0),

  CONSTRAINT ux_item_edge UNIQUE (parent_id, child_id)
);
CREATE INDEX ix_item_parent ON content_item (parent_id, position);
CREATE INDEX ix_item_child  ON content_item (child_id);

-- Per-set planned targets, when the sets differ from each other.
-- A table and not a JSON column, because the editor saves and deletes one set at a time.
CREATE TABLE content_item_set (
  content_item_id BIGINT  NOT NULL REFERENCES content_item(id) ON DELETE CASCADE,
  set_index       INTEGER NOT NULL,
  rep_index       INTEGER NOT NULL DEFAULT 0,
  reps            INTEGER,
  weight_kg       NUMERIC(6,2),
  seconds         INTEGER,
  PRIMARY KEY (content_item_id, set_index, rep_index),
  CONSTRAINT ck_set_index CHECK (set_index >= 1),
  CONSTRAINT ck_rep_index CHECK (rep_index >= 0)
);


-- A movement's OWN per-rep numbers, when its reps are not all the same. The mirror of
-- content_item_set one level up: that table holds what a block asks for, this one holds
-- what the movement is.
--
-- It exists because a movement can BE a ladder. A 3s, then 6s, then 9s hang is not a choice
-- a block makes about a plain hang; it is what the movement is, and its name says so.
-- Without this table such a shape could only be written inside one block, so no library
-- could hold one.
--
-- Other training apps keep their movement library plain and put non-uniform sets in the
-- workout. They can, because they also have a library of named protocols. The equivalent
-- here would be a block inside a block, which ck_item_pair forbids on purpose. See
-- docs/V2_PLAN.md 1.1 row 14.
--
-- Most movements need no row here.
CREATE TABLE content_set (
  content_id BIGINT  NOT NULL REFERENCES content(id) ON DELETE CASCADE,
  set_index  INTEGER NOT NULL,
  rep_index  INTEGER NOT NULL DEFAULT 0,
  reps       INTEGER,
  weight_kg  NUMERIC(6,2),
  seconds    INTEGER,
  PRIMARY KEY (content_id, set_index, rep_index),
  CONSTRAINT ck_content_set_index CHECK (set_index >= 1),
  CONSTRAINT ck_content_rep_index CHECK (rep_index >= 0)
);
-- A ladder lives here too: rungs of 3, 6 and 9 seconds are three rows, not the string
-- "3,6,9" in a column. That way the target and what you actually did are the same shape,
-- so the log can compare them without the app parsing anything.
--
-- rep_index is why the key has three columns. A ladder's rungs are REPS INSIDE ONE SET,
-- not sets, so (item, set) alone cannot hold them. An ordinary set is rep_index 0; a
-- three-rung ladder is set 1 with rep_index 1, 2, 3. This is in migration 001 because
-- SQLite cannot alter a primary key afterwards.

-- A person's own numbers for a movement they do not own.
--
-- The problem it solves: the app ships "Half Crimp Hang" and suggests 20 kg. You use 25.
-- Without this table the only way to record that is to copy the whole movement, which
-- creates a second row, a second identity, and a second history to reconcile. An override
-- creates none of those. The app's row stays the app's row, so a later release improving
-- its notes still reaches you, and your 25 kg still holds.
--
-- NULL means "no opinion about this number", not zero. Only the fields you set apply.
--
-- Resolution order for a number, weakest first:
--   1. the movement row's own d_* default
--   2. this table, for the account running the session
--   3. the content_item override on the slot being run
--   4. what the person enters while running
--
-- Level 3 beats level 2 because a slot is a prescription: a session that ramps 60/70/80%
-- must not collapse into one number. A shipped catalog file therefore must not set an
-- absolute weight_kg on an item; the importer refuses one, because it would silently
-- override this table for every account.
--
-- Keyed by movement_id and not by slug: the importer matches an existing row and UPDATEs
-- it, so an id survives every re-import and every rename. The constant movement_kind with
-- a composite foreign key is what makes "only a movement" declarative rather than a rule
-- in code, and it is the same shape plan_target already uses.
CREATE TABLE movement_pref (
  account_id    BIGINT      NOT NULL REFERENCES account(id) ON DELETE CASCADE,
  movement_id   BIGINT      NOT NULL,
  movement_kind VARCHAR(16) NOT NULL DEFAULT 'movement',

  sets              INTEGER,
  reps              INTEGER,
  weight_kg         NUMERIC(6,2),
  rep_seconds       INTEGER,
  rep_rest_seconds  INTEGER,
  set_rest_seconds  INTEGER,
  prep_seconds      INTEGER,
  seconds           INTEGER,

  created_at    TIMESTAMP   NOT NULL,
  updated_at    TIMESTAMP   NOT NULL,

  PRIMARY KEY (account_id, movement_id),
  CONSTRAINT ck_pref_kind CHECK (movement_kind = 'movement'),
  CONSTRAINT fk_pref_movement FOREIGN KEY (movement_id, movement_kind)
    REFERENCES content (id, kind) ON DELETE CASCADE
);

