-- Passion V2 schema. PostgreSQL and SQLite.
--
-- Conventions, and why:
--
--   Dates are VARCHAR(10) holding 'YYYY-MM-DD'. SQLite has no native DATE type, and a
--   fixed-width ISO string sorts and compares correctly on both engines. All date
--   arithmetic happens in Go. Timestamps are TIMESTAMP and are always UTC.
--
--   Fixed-width text is VARCHAR(n) with a length CHECK, never CHAR(n). PostgreSQL treats
--   CHAR as bpchar: it blank-pads on write and ignores trailing spaces on comparison, so
--   a Go "" is stored as 36 spaces there and as '' on SQLite. Same bug, two stored values,
--   and a query that matches on one engine and not the other. The CHECK is what actually
--   holds the width, and SQLite cannot add one later.
--
--   Integer primary keys are `BIGINT GENERATED BY DEFAULT AS IDENTITY` below, which is
--   PostgreSQL syntax. SQLite needs `INTEGER PRIMARY KEY AUTOINCREMENT` instead -- this is
--   the ONE construct in this file that cannot be spelled the same on both engines, and
--   GORM emits the correct form per dialect from a single `primaryKey` tag.
--
--   AUTOINCREMENT is required on SQLite, not optional: a plain INTEGER PRIMARY KEY reuses
--   row ids after a delete (tested -- id 1 was handed to a different row), so a deleted
--   session's id can silently come back attached to something else. That is why the log
--   never groups by an integer id: it groups by a family, which is minted once and is
--   never handed out again. Anything holding a bare id would rot.
--
--   Getting this wrong fails differently per engine: PostgreSQL raises a not-null
--   violation, SQLite accepts the insert and writes a NULL primary key.
--
--   Server-created rows use integer keys. The four log tables use UUID text keys, because
--   a phone with no signal has to invent them. Nothing else is ever client-created.
--
--   No soft deletes anywhere. Foreign keys and cascades do the work. SQLite needs
--   _foreign_keys=on in the DSN, on every pooled connection.
--
--   A NULL number means "not asked". Zero is a real value -- 0 kg is bodyweight.
--
--   Ordering columns are plain integers with no unique constraint. SQLite has no
--   deferrable constraints, so a two-row swap cannot be checked mid-statement. Reorders
--   rewrite every sibling in one transaction.


